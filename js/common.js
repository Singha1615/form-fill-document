const parts = (v) => {
  if (!v) return null;
  const [y, m, d] = String(v).split("-").map(Number);
  return y && m && d ? { y, m, d } : null;
};

/** 2026-11-23 -> "23 พฤศจิกายน 2569" */
export function thaiDate(v) {
  const p = parts(v);
  return p ? `${p.d} ${TH_MONTHS[p.m - 1]} ${p.y + 543}` : "";
}
/** 2026-11-23 -> "23 November 2026" */
export function enDate(v) {
  const p = parts(v);
  return p ? `${p.d} ${EN_MONTHS[p.m - 1]} ${p.y}` : "";
}
export function todayISO() {
  const t = new Date();
  const z = (n) => String(n).padStart(2, "0");
  return `${t.getFullYear()}-${z(t.getMonth() + 1)}-${z(t.getDate())}`;
}

